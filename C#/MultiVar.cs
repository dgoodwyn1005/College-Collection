internal class MultiVar
{
    public static void Main(string[] args)
    {
        object var;

        var = 1; //Integer
        Console.WriteLine(var);

        var = 10.3f; //Float
        Console.WriteLine(var);

        var = 'c'; //Char
        Console.WriteLine(var);

        var = "word"; //String
        Console.WriteLine(var);

    }
}
